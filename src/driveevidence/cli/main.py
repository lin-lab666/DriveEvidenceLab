"""Command-line interface for DriveEvidenceLab.

Subcommands:
    doctor   - environment diagnostics
    sample   - generate a sample scenario JSON
    run      - run a single episode and save evidence
    search   - run a search method and save evidence
    audit    - verify ledger and manifest integrity
    replay   - replay an archived episode
    report   - generate markdown/html report from a run
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

from driveevidence.evidence import (
    EpisodeStore,
    RunLedger,
    build_manifest,
    replay_episode,
    verify_manifest,
)
from driveevidence.evidence.ledger import LedgerError
from driveevidence.evidence.manifest import ManifestError
from driveevidence.report.generator import generate_html, generate_markdown
from driveevidence.scenario.ir import ScenarioIR, ScenarioValidationError, VehicleState
from driveevidence.search.base import Budget
from driveevidence.search.mutation_search import MutationSearch
from driveevidence.search.random_search import RandomSearch
from driveevidence.sim import create_adapter, list_adapters


def _project_root() -> Path:
    """Source checkout root if this is an editable/source run, else site-packages."""
    return Path(__file__).resolve().parents[3]


def _is_source_checkout(root: Path) -> bool:
    return (root / "pyproject.toml").exists() and (root / "src").is_dir()


def cmd_doctor(args: argparse.Namespace) -> int:
    """Print environment diagnostics.

    Works for both a source checkout and a wheel installation: reporting a
    site-packages directory as "project_root" would be misleading, so the label
    depends on what was actually found.
    """
    print("DriveEvidenceLab Doctor")
    print("=" * 40)
    root = _project_root()
    source = _is_source_checkout(root)
    if source:
        print(f"project_root: {root}")
        print(f"git repo: {(root / '.git').exists()}")
    else:
        # Installed from a wheel/sdist: there is no checkout to report.
        import driveevidence

        print(f"install mode: installed package (no source checkout)")
        print(f"package path: {Path(driveevidence.__file__).resolve().parent}")
        print("git repo: N/A (not a source checkout)")
    print(f"python: {sys.version.split()[0]}")
    deps = ["numpy", "scipy", "gymnasium", "highway_env", "commonroad"]
    for dep in deps:
        try:
            mod = __import__(dep)
            version = getattr(mod, "__version__", "unknown")
            print(f"{dep}: {version}")
        except ImportError:
            print(f"{dep}: NOT INSTALLED (optional)")
    print(f"registered adapters: {list_adapters()}")
    return 0


def _require_run_dir(path: str) -> Path:
    """Validate that ``path`` is an existing run directory holding a ledger."""
    run_dir = Path(path)
    if not run_dir.exists():
        raise FileNotFoundError(f"run directory not found: {path}")
    if not run_dir.is_dir():
        raise NotADirectoryError(f"not a directory: {path}")
    if not (run_dir / "ledger.jsonl").exists():
        raise LedgerError(f"no ledger.jsonl in {path} (not a DriveEvidenceLab run directory)")
    return run_dir


def _load_scenario(path: str) -> ScenarioIR:
    with open(path, "r", encoding="utf-8") as f:
        return ScenarioIR.from_dict(json.load(f))


def cmd_sample(args: argparse.Namespace) -> int:
    scenario = ScenarioIR(
        scenario_id=args.id,
        road_length_m=500.0,
        lanes=3,
        lane_width_m=3.7,
        speed_limit_mps=33.0,
        ego=VehicleState(
            id="ego", x_m=50.0, y_m=1.85, v_mps=25.0, heading_rad=0.0
        ),
        vehicles=[],
        meta={"description": "Sample scenario generated by CLI"},
    )
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(scenario.to_dict(), f, ensure_ascii=False, indent=2)
    print(f"Sample scenario written to {args.out}")
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    scenario = _load_scenario(args.scenario)
    adapter = create_adapter(args.adapter)
    run_dir = Path(args.out) / args.run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    config = {"adapter": args.adapter, "planner": args.planner, "command": "run"}
    ledger = RunLedger(str(run_dir), args.run_id, config=config)
    ledger.record(RunLedger.EVENT_EPISODE_STARTED, {"scenario_hash": scenario.scenario_hash})
    result = adapter.run_episode(scenario, seed=args.seed, planner_name=args.planner)
    ledger.record(
        RunLedger.EVENT_EPISODE_COMPLETED,
        {
            "scenario_hash": result.scenario_hash,
            "failure_category": result.failure_category.value,
            "steps": result.steps,
        },
    )
    store = EpisodeStore(str(run_dir))
    store.save(scenario, result, extra={"planner": args.planner})
    build_manifest(str(run_dir))
    print(
        f"Episode completed: {result.failure_category.value} "
        f"(steps={result.steps}, wall_time={result.wall_time_s:.3f}s)"
    )
    print(f"Evidence saved to {run_dir}")
    return 0


def cmd_search(args: argparse.Namespace) -> int:
    adapter = create_adapter(args.adapter)
    budget = Budget(max_episodes=args.budget)
    run_dir = Path(args.out) / args.run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    config: Dict[str, Any] = {
        "adapter": args.adapter,
        "method": args.method,
        "budget": args.budget,
        "command": "search",
    }
    ledger = RunLedger(str(run_dir), args.run_id, config=config)

    if args.method == "random":
        method = RandomSearch(road_length_m=500, lanes=3, max_steps=args.max_steps)
    elif args.method == "mutation":
        method = MutationSearch(road_length_m=500, lanes=3, max_steps=args.max_steps)
    else:
        print(f"Unknown method {args.method!r}", file=sys.stderr)
        return 1

    report = method.search(adapter, budget, master_seed=args.seed)
    ledger.record(
        RunLedger.EVENT_BUDGET_SNAPSHOT,
        {"snapshot": report.budget_snapshot, "n_candidates": len(report.candidates)},
    )
    store = EpisodeStore(str(run_dir))
    for candidate in report.candidates:
        scenario = ScenarioIR.from_dict(candidate.scenario_dict)
        result = adapter.run_episode(
            scenario, seed=candidate.discovery_seed, planner_name="safe_follow",
            config={"max_steps": args.max_steps},
        )
        store.save(scenario, result, extra={"candidate": True, "method": args.method})
    ledger.record(RunLedger.EVENT_RUN_FINISHED, {"n_episodes": report.n_episodes})
    build_manifest(str(run_dir))
    print(f"Search finished: {report.n_episodes} episodes, {len(report.candidates)} candidates")
    print(f"Evidence saved to {run_dir}")
    return 0


def cmd_audit(args: argparse.Namespace) -> int:
    run_dir = _require_run_dir(args.run)
    ledger = RunLedger.load(str(run_dir))
    ledger_ok, bad_seq = ledger.verify_chain()
    manifest_results = verify_manifest(str(run_dir))
    manifest_ok = manifest_results.get("__manifest__") == "ok" and all(
        v == "ok" for k, v in manifest_results.items() if k != "__manifest__"
    )
    print(f"Ledger integrity: {'PASS' if ledger_ok else 'FAIL'} (first_bad_seq={bad_seq})")
    print(f"Manifest integrity: {'PASS' if manifest_ok else 'FAIL'}")
    if not manifest_ok:
        for path, status in sorted(manifest_results.items()):
            if status != "ok":
                print(f"  {path}: {status}")
    return 0 if ledger_ok and manifest_ok else 1


def cmd_replay(args: argparse.Namespace) -> int:
    run_dir = _require_run_dir(args.run)
    adapter = create_adapter(args.adapter)
    outcome = replay_episode(str(run_dir), args.seq, adapter)
    print(f"Original category: {outcome.original_category}")
    print(f"Replayed category: {outcome.replayed_category}")
    print(f"Category match: {outcome.category_match}")
    print(f"Metric diffs: {outcome.metric_diffs}")
    if not outcome.category_match:
        # A mismatch is a reproducibility failure, not merely information: an
        # exit code of 0 here would let CI silently accept a broken replay.
        print(
            "WARNING: replayed category differs from the archived episode; "
            "this run is NOT reproducible under the current environment/backend.",
            file=sys.stderr,
        )
        return 1
    return 0


def cmd_report(args: argparse.Namespace) -> int:
    run_dir = _require_run_dir(args.run)
    if args.format == "md":
        generate_markdown(str(run_dir), args.out)
    elif args.format == "html":
        generate_html(str(run_dir), args.out)
    else:
        print(f"Unknown format {args.format!r}", file=sys.stderr)
        return 1
    print(f"Report written to {args.out}")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="driveevidence", description="DriveEvidenceLab CLI")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("doctor", help="environment diagnostics")
    p.set_defaults(func=cmd_doctor)

    p = sub.add_parser("sample", help="generate a sample scenario")
    p.add_argument("--id", default="sample")
    p.add_argument("--out", default="scenario.json")
    p.set_defaults(func=cmd_sample)

    p = sub.add_parser("run", help="run a single episode")
    p.add_argument("--scenario", required=True)
    p.add_argument("--adapter", default="builtin")
    p.add_argument("--planner", default="safe_follow")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--run-id", default=f"run_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}")
    p.add_argument("--out", default="runs")
    p.set_defaults(func=cmd_run)

    p = sub.add_parser("search", help="run a search method")
    p.add_argument("--method", choices=["random", "mutation"], required=True)
    p.add_argument("--adapter", default="builtin")
    p.add_argument("--budget", type=int, default=32)
    p.add_argument("--seed", type=int, default=2000)
    p.add_argument("--max-steps", type=int, default=80)
    p.add_argument("--run-id", default=f"search_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}")
    p.add_argument("--out", default="runs")
    p.set_defaults(func=cmd_search)

    p = sub.add_parser("audit", help="verify ledger and manifest")
    p.add_argument("--run", required=True)
    p.set_defaults(func=cmd_audit)

    p = sub.add_parser("replay", help="replay an archived episode")
    p.add_argument("--run", required=True)
    p.add_argument("--seq", type=int, required=True)
    p.add_argument("--adapter", default="builtin")
    p.set_defaults(func=cmd_replay)

    p = sub.add_parser("report", help="generate report from a run")
    p.add_argument("--run", required=True)
    p.add_argument("--format", choices=["md", "html"], default="md")
    p.add_argument("--out", required=True)
    p.set_defaults(func=cmd_report)

    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130
    except Exception as exc:  # noqa: BLE001 - CLI boundary, re-raised in debug mode
        # Bad input (missing path, malformed JSON, broken ledger) is a user error,
        # not a crash. Set DRIVEEVIDENCE_DEBUG=1 to get the original traceback.
        if os.environ.get("DRIVEEVIDENCE_DEBUG"):
            raise
        expected = (
            LedgerError,
            ManifestError,
            ScenarioValidationError,
            FileNotFoundError,
            NotADirectoryError,
            OSError,
            ValueError,
            KeyError,
        )
        if isinstance(exc, expected):
            print(f"error: {exc}", file=sys.stderr)
        else:
            # An unexpected exception type is a bug in this package, not bad input.
            # Report it distinctly so it is never mistaken for a user mistake.
            print(
                f"internal error: {type(exc).__name__}: {exc}\n"
                f"(set DRIVEEVIDENCE_DEBUG=1 for a full traceback; "
                f"this is a bug, please report it)",
                file=sys.stderr,
            )
        return 2


if __name__ == "__main__":
    sys.exit(main())
